/** 清洗选中文本：去首尾标点、只保留单个词（允许中日韩等字符），不是单词则返回 null */
export function sanitizeWord(raw: string): string | null {
  let w = raw.trim()
  // 去首尾非字母数字字符（。，、！？,.!?;:'"()[]「」『』…·）
  w = w.replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, '')
  if (!w || w.length > 40 || /\s/.test(w)) return null // 太长 / 含空格 → 不是单个词
  return w
}
